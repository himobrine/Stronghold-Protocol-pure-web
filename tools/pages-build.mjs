// tools/pages-build.mjs — assemble the static site a plain CDN / GitHub Pages serves (pure-web fork).
//
// The Node server mounts four trees (server/http/static.js): public/ at /, data/ at /data/,
// shared/ at /shared/ and server/sim/*.js at /sim/, plus a generated /data.js stand-in for the
// sim's content modules. This script copies those into one output folder and rewrites every
// root-absolute reference (`"/css/…"`, `from '/shared/…'`, CSS `url(/fonts/…)`, the importmap …)
// to sit under the Pages base path, since a project site is served from /<repo-name>/.
//
// Game art (public/assets, public/fonts) is never in git and is not copied; the client falls back
// as it does on a server without local art (docs/DEPLOY.md §6). public/vendor IS needed and comes
// from `npm ci` (postinstall → tools/vendor.mjs).
//
// Run: node tools/pages-build.mjs --base /Stronghold-Protocol-pure-web [--out _site]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

// The browser stand-in of server/data.js, byte-identical in behaviour to DATA_SHIM_JS in
// server/http/static.js (kept inline so this tool never imports the server's HTTP stack).
const DATA_SHIM_JS = `// Generated by tools/pages-build.mjs — browser stand-in for server/data.js (DESIGN §14 client-side combat).
// The simulation's content modules (/sim/content/support/index.js) import getData() from here; it returns the game data
// the page injected with /sim/simdata.js setSimData(data).
import { getSimData } from './sim/simdata.js';
export function getData() { return getSimData() || {}; }
export function resetData() {}
`;

/** Root-absolute URL prefixes the server mounts (plus the folders of public/ a page may name). */
const ABS_PREFIXES = ['css', 'js', 'vendor', 'data', 'shared', 'sim', 'i18n', 'icons', 'fonts',
  'manifest', 'packs', 'assets', 'media', 'dev'];

/** Rewrite `"/prefix…` / `'/prefix…` / `` `/prefix… `` / `url(/prefix…` to `${base}/prefix…`. */
function rewriteAbs(text, base) {
  const re = new RegExp(`(["'\`(?:])\\/(${ABS_PREFIXES.join('|')})(?![\\w-])`, 'g');
  return text.replace(re, (m, quote, name) => `${quote}${base}/${name}`);
}

/**
 * Relative import specifiers that climb to the site root carry one '..' too many: on the server
 * the URL clamp at `/` swallowed it (`../../shared/x.js` from /js/ → /shared/x.js). Under a base
 * path that extra '..' escapes the site instead, so drop one from every over-deep specifier.
 * Only real import / export / import() specifiers are touched — never page-relative strings.
 */
function rewriteRel(text, depth) {
  const re = /(\b(?:from|import)\s*\(?\s*)(['"])((?:\.\.\/)+)([^'"]*)\2/g;
  return text.replace(re, (m, head, quote, ups, rest) => {
    const n = ups.length / 3;
    return n > depth ? `${head}${quote}${'../'.repeat(n - 1)}${rest}${quote}` : m;
  });
}

/** URL-style normalize ("a/b/../c" → "a/c"). */
function normalizeUrl(p) {
  const out = [];
  for (const seg of p.split('/')) {
    if (seg === '' || seg === '.') continue;
    if (seg === '..') out.pop();
    else out.push(seg);
  }
  return `/${out.join('/')}`;
}

/**
 * Every relative / absolute import of a shipped module must stay inside the site after the
 * rewrite — a leftover escape (a specifier the patterns missed) fails the build instead of
 * the first page load.
 */
function checkEscapes(out, base) {
  const SPEC = /\b(?:from|import)\s*\(?\s*(['"])([^'"]+)\1/g;
  const problems = [];
  for (const file of walk(out)) {
    const rel = path.relative(out, file).split(path.sep).join('/');
    if (rel.startsWith('vendor/') || rel.endsWith('.min.js')) continue;
    if (!/\.(?:js|mjs|html)$/.test(file)) continue;
    const dir = rel.includes('/') ? rel.slice(0, rel.lastIndexOf('/')) : '';
    for (const m of fs.readFileSync(file, 'utf8').matchAll(SPEC)) {
      const spec = m[2];
      let abs;
      if (spec.startsWith('/')) abs = normalizeUrl(spec);
      else if (spec.startsWith('.')) abs = normalizeUrl(`${base}/${dir}/${spec}`);
      else continue; // bare specifier — the import map owns it
      if (abs !== base && !abs.startsWith(`${base}/`)) problems.push(`${rel}: '${spec}' → ${abs}`);
    }
  }
  return problems;
}

/**
 * Recursive copy without fs.cpSync: on some Windows setups (Node 24 + non-ASCII paths) cpSync
 * dies natively inside the recursion — no JS error, partial output. copyFileSync is stable.
 */
function copyTree(src, dest, keep = () => true) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (!keep(entry.name)) continue;
    const from = path.join(src, entry.name);
    if (entry.isDirectory()) copyTree(from, path.join(dest, entry.name), keep);
    else fs.copyFileSync(from, path.join(dest, entry.name));
  }
}

/** Copy server/sim/*.js → out/sim/, skipping the Node-only loader (SIM_PRIVATE in static.js). */
function copySim(srcDir, destDir) {
  fs.mkdirSync(destDir, { recursive: true });
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    if (entry.name.toLowerCase() === 'nodedata.js') continue;
    const src = path.join(srcDir, entry.name);
    if (entry.isDirectory()) copySim(src, path.join(destDir, entry.name));
    else if (entry.name.endsWith('.js')) fs.copyFileSync(src, path.join(destDir, entry.name));
  }
}

/** Every file under dir (depth-first). */
function walk(dir, into = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, into);
    else into.push(p);
  }
  return into;
}

function parseArgs(argv) {
  const args = { base: '', out: path.join(ROOT, '_site') };
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === '--base') args.base = argv[++i] || '';
    else if (argv[i] === '--out') args.out = path.resolve(argv[++i]);
    else throw new Error(`pages-build: unknown argument ${argv[i]}`);
  }
  if (args.base && !args.base.startsWith('/')) args.base = `/${args.base}`;
  if (args.base.endsWith('/')) args.base = args.base.slice(0, -1);
  return args;
}

function main() {
  const { base, out } = parseArgs(process.argv);
  fs.rmSync(out, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  if (fs.existsSync(out)) throw new Error(`pages-build: cannot remove ${out} (a file is held open?)`);
  fs.mkdirSync(out, { recursive: true });

  // public/ without the game-art folders (never in git; the client falls back, DEPLOY.md §6)
  copyTree(path.join(ROOT, 'public'), out, (name) => name !== 'assets' && name !== 'local-assets.json');
  copyTree(path.join(ROOT, 'shared'), path.join(out, 'shared'));
  copyTree(path.join(ROOT, 'data'), path.join(out, 'data'), (name) => name !== 'local-assets.json');
  copySim(path.join(ROOT, 'server', 'sim'), path.join(out, 'sim'));
  fs.writeFileSync(path.join(out, 'data.js'), DATA_SHIM_JS);
  fs.writeFileSync(path.join(out, '.nojekyll'), '');

  // Rewrite the text files a page loads. vendor/ and *.min.js are third-party bundles: skipped
  // for speed and to keep their bytes intact. JSON other than the web manifest holds game data,
  // not URLs — only manifest.json needs both the prefix rewrite and its "/" fields.
  const TEXT = new Set(['.html', '.js', '.mjs', '.css']);
  let rewritten = 0;
  for (const file of walk(out)) {
    const relParts = path.relative(out, file).split(path.sep);
    if (relParts[0] === 'vendor' || file.endsWith('.min.js')) continue;
    const isManifest = relParts.length === 1 && relParts[0] === 'manifest.json';
    if (!TEXT.has(path.extname(file)) && !isManifest) continue;
    const src = fs.readFileSync(file, 'utf8');
    let dst = src;
    if (base) {
      dst = rewriteAbs(dst, base);
      const depth = Math.max(0, relParts.length - 2); // directories the file sits under out/
      dst = rewriteRel(dst, depth);
    }
    if (isManifest && base) {
      const man = JSON.parse(dst);
      man.id = `${base}/`;
      man.start_url = `${base}/`;
      man.scope = `${base}/`;
      dst = `${JSON.stringify(man, null, 2)}\n`;
    }
    if (dst !== src) {
      fs.writeFileSync(file, dst);
      rewritten++;
    }
  }

  if (base) {
    const problems = checkEscapes(out, base);
    if (problems.length) {
      console.error(`pages-build: ${problems.length} import(s) still escape the site:`);
      for (const p of problems) console.error(`  ${p}`);
      throw new Error('pages-build: import escapes (see above)');
    }
  }

  const files = walk(out);
  const bytes = files.reduce((n, f) => n + fs.statSync(f).size, 0);
  console.log(`pages-build: ${files.length} files, ${(bytes / 1024 / 1024).toFixed(1)} MB in ${path.relative(ROOT, out) || out}`
    + `${base ? `, base ${base}` : ''} (${rewritten} files rewritten)`);
}

main();
